#!/usr/bin/env bash
# firm-heartbeat.sh
#
# Skriver heartbeat for én pane til Obsidian Brain sin pane-status-mappe.
# Trigges av paner (manuelt, fra session-context, eller via en bakgrunns-loop).
# Tar ingen args; leser miljø-variabler satt av firm-tab-init.sh.
#
# Output:
#   - JSON:  ~/Obsidian/Brain/00-firm-bus/pane-status/<role>.json
#            (for maskin-bruk, scripts, V2 TUI)
#   - .md:   ~/Obsidian/Brain/00-firm-bus/pane-status/<role>.md
#            (for Dataview-bruk; frontmatter med samme felter)
#
# Begge writes er atomiske (tmpfile + mv).
# Exit 0 stille hvis FIRM_ROLE ikke er satt (kall fra ikke-firm-shell skal ikke
# støye).

set -euo pipefail

# Stille no-op hvis ikke i firm-pane.
if [[ -z "${FIRM_ROLE:-}" ]]; then
  exit 0
fi

ROLE="${FIRM_ROLE}"
PROJECT="${FIRM_PROJECT:-unknown}"
HOSTNAME_VAL="$(hostname)"
PID_VAL="$$"
CWD_VAL="$(pwd)"
NOW_ISO="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

# claude --version kan være treigt; fang stille feil og fall tilbake til "unknown".
CLAUDE_VERSION="unknown"
if command -v claude >/dev/null 2>&1; then
  CLAUDE_VERSION="$(claude --version 2>/dev/null | head -1 | tr -d '\n' || true)"
  [[ -z "$CLAUDE_VERSION" ]] && CLAUDE_VERSION="unknown"
fi

OPENED_AT="${FIRM_TAB_OPENED_AT:-$NOW_ISO}"

STATUS_DIR="${HOME}/Obsidian/Brain/00-firm-bus/pane-status"
mkdir -p "$STATUS_DIR"

JSON_DEST="${STATUS_DIR}/${ROLE}.json"
MD_DEST="${STATUS_DIR}/${ROLE}.md"

# --- JSON-skriv (atomic) ---
JSON_TMP="$(mktemp "${STATUS_DIR}/.${ROLE}.json.XXXXXX")"
trap 'rm -f "$JSON_TMP" "$MD_TMP" 2>/dev/null || true' EXIT

jq -n \
  --arg role "$ROLE" \
  --arg project "$PROJECT" \
  --argjson pid "$PID_VAL" \
  --arg hostname "$HOSTNAME_VAL" \
  --arg last_heartbeat "$NOW_ISO" \
  --arg opened_at "$OPENED_AT" \
  --arg cwd "$CWD_VAL" \
  --arg claude_version "$CLAUDE_VERSION" \
  '{
    role: $role,
    project: $project,
    pid: $pid,
    hostname: $hostname,
    last_heartbeat: $last_heartbeat,
    opened_at: $opened_at,
    cwd: $cwd,
    claude_version: $claude_version
  }' > "$JSON_TMP"

mv -f "$JSON_TMP" "$JSON_DEST"

# --- Markdown-skriv (frontmatter for Dataview, atomic) ---
MD_TMP="$(mktemp "${STATUS_DIR}/.${ROLE}.md.XXXXXX")"

cat > "$MD_TMP" <<EOF
---
type: pane-status
role: ${ROLE}
project: ${PROJECT}
pid: ${PID_VAL}
hostname: ${HOSTNAME_VAL}
last_heartbeat: ${NOW_ISO}
opened_at: ${OPENED_AT}
cwd: "${CWD_VAL}"
claude_version: "${CLAUDE_VERSION}"
tags: [pane-status, firm-bus]
---

# Pane status: \`${ROLE}\`

- **Project**: ${PROJECT}
- **Host**: ${HOSTNAME_VAL}
- **PID**: ${PID_VAL}
- **CWD**: \`${CWD_VAL}\`
- **Opened**: ${OPENED_AT}
- **Last heartbeat**: ${NOW_ISO}
- **Claude**: ${CLAUDE_VERSION}

Auto-generated by \`_bin/firm-heartbeat.sh\`. Do not edit by hand.
EOF

mv -f "$MD_TMP" "$MD_DEST"

trap - EXIT
exit 0
